	/** The column names of a table. */
	public static function columns(string $table): array
	{
		return array_keys(self::TABLES[$table]);
	}

	/** CREATE TABLE for a table, keyed by <singular>_uuid as FusionPBX's save() is. */
	public static function createTable(string $table): string
	{
		$key = substr(rtrim($table, 's'), 2).'_uuid';
		$columns = array();
		foreach (self::TABLES[$table] as $column => $type) {
			$columns[] = $column.' '.$type.($column === $key ? ' PRIMARY KEY' : '');
		}
		return 'CREATE TABLE IF NOT EXISTS '.$table.' ('.implode(', ', $columns).')';
	}
